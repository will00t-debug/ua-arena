 const s=state(),pl=s.players[0];pl.energy[0]=c('generator','TTG-1-066',{gen:10});
 pl.front[0]=c('old','TTG-1-076',{stack:[c('simon','TTG-1-051')]});
 pl.front[1]=c('nia','TTG-1-059');

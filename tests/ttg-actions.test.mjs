import test from 'node:test';
import assert from 'node:assert/strict';
import {canDeployTtgCard,eligibleGigaDrillTargets,resolveGigaDrillRetire,readyTtgApCards,spendTtgApCards,markTtgOncePerName} from '../dist/ttg-actions.mjs';
const ch=(uid,cardId,nameJa,bp=1500,extras={})=>({uid,cardId,nameJa,bp,...extras});
const blank=()=>({front:Array(4).fill(null),energy:Array(4).fill(null),outside:[],apCards:[{uid:'AP1',ready:true},{uid:'AP2',ready:false},{uid:'AP3',ready:true}]});
const game=()=>({players:[blank(),blank()]});
test('red Nia and Kamina mutually prohibit their own deployments, including Raid bases',()=>{
 const board=blank(),nia=ch('n','TTG-1-059','ニア');
 const kamina=ch('k','TTG-1-042','カミナ');
 board.front[0]=kamina;
 assert.equal(canDeployTtgCard(board,nia),false);
 assert.equal(canDeployTtgCard(board,ch('g','TTG-1-015','ニア')),true,'green Nia has no prohibition');
 board.front[0]=null;
 board.energy[1]=ch('r','TTG-1-072','グレン',4000,{stack:[kamina]});
 assert.equal(canDeployTtgCard(board,nia),false,'public base counts');
 board.energy[1]=null;
 board.front[0]=nia;
 assert.equal(canDeployTtgCard(board,kamina),false);
 board.front[0]=ch('r','TTG-1-074','グレンラガン',4000,{stack:[nia]});
 assert.equal(canDeployTtgCard(board,kamina),false);
 board.front[0]=ch('r','TTG-1-074','グレンラガン',4000,{under:[{uid:'n',cardId:'TTG-1-059',nameJa:'ニア',faceDown:true}]});
 assert.equal(canDeployTtgCard(board,kamina),true,'faccedown cards do not count as printed Raid bases');
});
test('Q2301 corrected Giga Drill cannot select energy, friendly or BP over limit',()=>{
 let s=game();
 s.players[1].front[0]=ch('a','A','A',3000);
 s.players[1].front[1]=ch('b','B','B',5000);
 s.players[1].energy[0]=ch('e','E','E',1000);
 assert.deepEqual(eligibleGigaDrillTargets(s,0).map(c=>c.uid),['a']);
 assert.throws(()=>resolveGigaDrillRetire(s,{player:0,targetUid:'e'}));
 assert.throws(()=>resolveGigaDrillRetire(s,{player:0,targetUid:'b'}));
 s.players[0].energy[0]=ch('s','TTG-1-009','シモン');
 assert.deepEqual(eligibleGigaDrillTargets(s,0).map(c=>c.uid),['a','b']);
 let x=resolveGigaDrillRetire(s,{player:0,targetUid:'b'});
 assert.equal(x.players[1].front[1],null);
 assert.deepEqual(x.players[1].outside,[{uid:'b',cardId:'B'}]);
 assert.equal(s.players[1].front[1].uid,'b','immutable original');
});
test('Q2276 effect-targeting immunity excludes otherwise legal BP targets',()=>{
 const s=game();
 s.players[1].front[0]=ch('a','TTG-1-031','超銀河グレンラガン',5000,{cannotBeChosen:true});
 s.players[1].front[1]=ch('b','TTG-1-001','ヴィラル',2500,{protectedFromEffects:true});
 s.players[1].front[2]=ch('c','TTG-1-005','キタン',3000);
 s.players[0].energy[1]=ch('s','TTG-1-010','シモン');
 assert.deepEqual(eligibleGigaDrillTargets(s,0).map(x=>x.uid),['c']);
 assert.throws(()=>resolveGigaDrillRetire(s,{player:0,targetUid:'a'}));
 assert.throws(()=>resolveGigaDrillRetire(s,{player:0,targetUid:'b'}));
});
test('Giga Drill recognizes Simon/Kamina Raid bases and retires whole Raid pile without loss',()=>{
 const s=game();
 s.players[0].front[0]=ch('r','TTG-1-073','グレンラガン',4000,{stack:[ch('k','TTG-1-042','カミナ')]});
 s.players[1].front[2]=ch('top','TTG-1-032','天元突破グレンラガン',5000,{stack:[ch('base','TTG-1-010','シモン')],under:[{uid:'under',cardId:'TTG-1-027',faceDown:true}]});
 let x=resolveGigaDrillRetire(s,{player:0,targetUid:'top'});
 assert.deepEqual(x.players[1].outside.map(y=>y.uid),['top','base','under']);
 assert.equal(x.players[1].front[2],null);
 assert.throws(()=>resolveGigaDrillRetire(x,{player:0,targetUid:'top'}));
});
test('AP rest costs, ACTIVE recovery and serializable AP state',()=>{
 let s=game();
 s=spendTtgApCards(s,{player:0,apUids:['AP1'],count:1});
 assert.equal(s.players[0].apCards[0].ready,false);
 assert.throws(()=>spendTtgApCards(s,{player:0,apUids:['AP1'],count:1}));
 assert.throws(()=>spendTtgApCards(s,{player:0,apUids:['AP2'],count:1}));
 assert.throws(()=>readyTtgApCards(s,{player:0,apUids:['AP1','AP1']}));
 assert.throws(()=>readyTtgApCards(s,{player:0,apUids:['AP1','AP2','AP3']}));
 assert.throws(()=>readyTtgApCards(s,{player:0,apUids:['AP4']}));
 const u=readyTtgApCards(s,{player:0,apUids:['AP1','AP2']});
 assert.deepEqual(u.players[0].apCards.map(c=>c.ready),[true,true,true]);
 assert.equal(s.players[0].apCards[0].ready,false);
 assert.equal(u.players[1].apCards[1].ready,false,'other player unchanged');
});
test('multiple same-name copies share once-per-turn limit but reset next turn',()=>{
 let s=game();s=markTtgOncePerName(s,{player:0,turn:4,name:'ヴィラル',ability:'activate20'});
 assert.throws(()=>markTtgOncePerName(s,{player:0,turn:4,name:'ヴィラル',ability:'activate20'}));
 let x=markTtgOncePerName(s,{player:0,turn:4,name:'ヴィラル',ability:'frontEnergy'});
 x=markTtgOncePerName(x,{player:1,turn:4,name:'ヴィラル',ability:'activate20'});
 x=markTtgOncePerName(x,{player:0,turn:5,name:'ヴィラル',ability:'activate20'});
 assert.ok(x.players[0].usedTtgEffects['5:ヴィラル:activate20']);
 assert.equal(s.players[0].usedTtgEffects['5:ヴィラル:activate20'],undefined);
});

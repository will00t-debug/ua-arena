import test from 'node:test';
import assert from 'node:assert/strict';
import {beginRed073Leaving,legalRed073Leaving,resolveRed073Leaving} from '../dist/ttg-red-073-leaving.mjs';
import {TTG_BY_ID} from '../dist/ttg-builder.mjs';
import {newTtgCoreMatch,legalTtgCoreActions,dispatchTtgCoreAction,assertTtgCoreState} from '../dist/ttg-core-match.mjs';
import {withTtgDerivedEnergy} from '../dist/ttg-energy-snapshot.mjs';
import {legalRed056End,resolveRed056End} from '../dist/ttg-red-056-after-attack.mjs';
const c=(uid,id,extra={})=>({uid,cardId:id,ready:true,stack:[],under:[],...extra});
const pl=()=>({front:[null,null,null,null],energy:[null,null,null,null],hand:[],deck:[],life:[],outside:[],removed:[]});
const s=()=>({turn:9,active:0,phase:'attack',status:'playing',players:[pl(),pl()]});
const uids=p=>[...p.front.filter(Boolean),...p.energy.filter(Boolean),...p.hand,...p.deck,...p.life,...p.outside,...p.removed].flatMap(function f(c){return [c.uid,...(c.stack||[]).flatMap(f),...(c.under||[]).flatMap(f)]}).sort();
test('073 leaving by battle/event offers optional face-down replacement with no card duplication',()=>{
 const st=s(),def=st.players[1];
 def.front[0]=c('top','TTG-1-073',{stack:[c('base','TTG-1-051')],under:[c('hidden','TTG-1-072',{faceDown:true})]});
 const initial=uids(def);
 let r=beginRed073Leaving(st,{player:1,uid:'top'});
 assert.deepEqual(legalRed073Leaving(r).map(x=>x.mode),['retire','replace']);
 r=resolveRed073Leaving(r,legalRed073Leaving(r).find(x=>x.mode==='replace'));
 assert.equal(r.players[1].front[0].uid,'top');
 assert.equal(r.players[1].front[0].under.length,0);
 assert.equal(r.players[1].outside[0].uid,'hidden');
 assert.equal(r.players[1].outside[0].faceDown,false);
 assert.deepEqual(uids(r.players[1]),initial);
 const st2=beginRed073Leaving(st,{player:1,uid:'top'});
 const retired=resolveRed073Leaving(st2,legalRed073Leaving(st2).find(x=>x.mode==='retire'));
 assert.equal(retired.players[1].front[0],null);
 assert.deepEqual(uids(retired.players[1]),initial);
});
test('056 Q2291/Q2292 pending after damage, then can Raid 076 with +1000 and actual top2 choice',()=>{
 const st=s(),p=st.players[0];
 p.front[0]=c('source','TTG-1-056');p.front[1]=c('nia','TTG-1-059');
 p.hand=[c('lagan','TTG-1-076')];p.deck=[c('top1','TTG-1-042'),c('top2','TTG-1-043')];
 st.pending={kind:'ttgRed056AfterAttack',player:0,uid:'source'};
 const before=uids(p);
 assert.deepEqual(legalRed056End(st).map(x=>x.mode),['decline','raid']);
 const choice=legalRed056End(st).find(x=>x.mode==='raid');
 const r=resolveRed056End(st,choice);
 assert.equal(r.players[0].front[0].cardId,'TTG-1-076');
 assert.equal(r.players[0].front[0].currentBp,4000);
 assert.equal(r.pending.kind,'ttgRedRaidQueue');
 assert.ok(r.raidNamesThisTurn.includes('ラガン'));
 assert.deepEqual(uids(r.players[0]),before);
 const repeat=s();repeat.players[0].front[0]=c('source','TTG-1-056');
 repeat.players[0].hand=[c('lagan','TTG-1-076')];repeat.pending={kind:'ttgRed056AfterAttack',player:0,uid:'source'};
 repeat.raidNamesThisTurn=['ラガン'];
 assert.deepEqual(legalRed056End(repeat).map(x=>x.mode),['decline']);
});
test('073 battle replacement is a defender choice after blocked attack, not automatic retirement',()=>{
 const d=Object.fromEntries(['042','043','051','052','056','059','061','062','066','072','074','076'].map(n=>['TTG-1-'+n,4]).concat([['TTG-1-073',1],['TTG-1-078',1]]));
 const find=(p,id)=>{for(const zone of ['hand','deck','life','outside']){const i=p[zone].findIndex(x=>x.cardId===id);if(i>=0)return p[zone].splice(i,1)[0];}throw Error(id)};
 let state=newTtgCoreMatch({decks:[d,d],seed:733});state.phase='attack';state.turn=6;
 state.players[0].turnCount=3;
 const atk={...find(state.players[0],'TTG-1-072'),ready:true,currentBp:8000};
 state.players[0].front[0]=atk;
 const def=state.players[1],top=find(def,'TTG-1-073'),base=find(def,'TTG-1-051'),under=find(def,'TTG-1-072');
 def.front[0]={...top,ready:true,stack:[base],under:[{...under,faceDown:true}]};
 state=withTtgDerivedEnergy(withTtgDerivedEnergy(state,0),1);
 let a=legalTtgCoreActions(state).find(x=>x.type==='attack'&&x.uid===atk.uid);
 assert.ok(a);state=dispatchTtgCoreAction(state,a);
 a=legalTtgCoreActions(state).find(x=>x.type==='block'&&x.blockUid===top.uid);
 assert.ok(a);state=dispatchTtgCoreAction(state,a);
 assert.equal(state.pending.kind,'ttgRed073Leaving');
 a=legalTtgCoreActions(state).find(x=>x.mode==='replace');
 assert.ok(a);state=dispatchTtgCoreAction(state,a);
 assert.equal(state.players[1].front[0].uid,top.uid);
 assert.equal(state.players[1].front[0].under.length,0);
 assert.equal(state.players[1].outside.some(x=>x.uid===under.uid),true);
 assert.ok(assertTtgCoreState(state));
});

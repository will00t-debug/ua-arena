import test from 'node:test';
import assert from 'node:assert/strict';
import {legalGreenEventActions,resolveGreenEvent,legalGreen040RemovedActions,resolveGreen040Removed,resolveGreenEventTurnEnd} from '../dist/ttg-green-events.mjs';
import {legalTtgRuleActions,dispatchTtgRuleAction,resolveTtgTurnEnd,chooseTtgRuleAiAction} from '../dist/ttg-rule-adapter.mjs';
import {TTG_BY_ID} from '../dist/ttg-builder.mjs';
const c=(uid,id,extra={})=>({uid,cardId:id,nameJa:TTG_BY_ID[id]?.nameJa,ready:true,stack:[],under:[],...extra});
const p=()=>({front:[null,null,null,null],energy:[null,null,null,null],hand:[],deck:[],outside:[],removed:[],life:[],apCards:[{uid:'ap',ready:true},{uid:'rest',ready:false}],energyProduced:{green:8,red:0}});
const s=()=>({phase:'main',active:0,turn:4,energyMode:'external',players:[p(),p()],log:[]});
const ids=p=>[...p.hand,...p.deck,...p.outside,...p.removed,...p.life,...p.front.filter(Boolean),...p.energy.filter(Boolean)].flatMap(function x(c){return [c.uid,...(c.stack||[]).flatMap(x),...(c.under||[]).flatMap(x)]}).sort();
const use=(state,id,extra={})=>resolveGreenEvent(state,{player:0,handUid:'event',cardId:id,payApUids:['ap'],...extra});
test('035 removal normal effect front BP≤3000; Simon/base upgrades threshold to 5000',()=>{
 const st=s();st.players[0].hand=[c('event','TTG-1-035')];
 st.players[1].front[0]=c('lo','TTG-1-006',{bp:2500});
 st.players[1].front[1]=c('hi','TTG-1-027',{bp:4000});
 st.players[1].energy[0]=c('notFront','TTG-1-005',{bp:1000});
 let choices=legalGreenEventActions(st,0);
 assert.deepEqual(choices.map(a=>a.targetUid),['lo']);
 assert.throws(()=>use(st,'TTG-1-035',{targetUid:'hi'}));
 assert.throws(()=>use(st,'TTG-1-035',{targetUid:'notFront'}));
 st.players[0].front[0]=c('s','TTG-1-009');
 choices=legalGreenEventActions(st,0);
 assert.deepEqual(choices.map(a=>a.targetUid),['lo','hi']);
 const origin=JSON.stringify(st),before=ids(st.players[1]);
 const out=use(st,'TTG-1-035',{targetUid:'hi'});
 assert.equal(out.players[1].front[1],null);
 assert.deepEqual(out.players[1].removed.map(x=>x.uid),['hi']);
 assert.equal(out.players[1].energy[0].uid,'notFront');
 assert.deepEqual(ids(out.players[1]),before);
 assert.deepEqual(out.players[0].outside.map(x=>x.uid),['event']);
 assert.equal(out.players[0].apCards[0].ready,false);
 assert.equal(JSON.stringify(st),origin);
});
test('039 targets own Simon/Lagann and grants maximum current allied BP and Impact 1',()=>{
 const st=s();st.players[0].hand=[c('event','TTG-1-039')];
 st.players[0].front[0]=c('sim','TTG-1-009');
 st.players[0].front[1]=c('strong','TTG-1-027',{currentBp:6000});
 st.players[0].energy[0]=c('not','TTG-1-005');
 assert.deepEqual(legalGreenEventActions(st,0).map(x=>x.targetUid),['sim','strong']);
 assert.throws(()=>use(st,'TTG-1-039',{targetUid:'not'}));
 const r=use(st,'TTG-1-039',{targetUid:'sim'});
 assert.equal(r.players[0].front[0].currentBp,TTG_BY_ID['TTG-1-009'].bp+6000);
 assert.equal(r.players[0].front[0].greenEventImpact,1);
 const end=resolveTtgTurnEnd(r);
 assert.equal(end.players[0].front[0].currentBp,TTG_BY_ID['TTG-1-009'].bp);
 assert.equal(end.players[0].front[0].greenEventImpact,0);
});
test('041 distinct printed names; 3 selected gain 3000 EACH, duplicate name forbidden',()=>{
 const st=s();st.players[0].hand=[c('event','TTG-1-041')];
 st.players[0].front=[c('a','TTG-1-009'),c('b','TTG-1-010'),c('c','TTG-1-006'),c('d','TTG-1-023')];
 const legal=legalGreenEventActions(st,0);
 assert.ok(!legal.some(x=>x.targetUids?.includes('a')&&x.targetUids?.includes('b')),'same name Simon prohibited');
 const action=legal.find(x=>JSON.stringify(x.targetUids)==='["a","c","d"]');
 assert.ok(action);
 const r=use(st,'TTG-1-041',{targetUids:action.targetUids});
 for(const uid of ['a','c','d']){
  const before=st.players[0].front.find(x=>x.uid===uid);
  const after=r.players[0].front.find(x=>x.uid===uid);
  assert.equal(after.currentBp,TTG_BY_ID[before.cardId].bp+3000);
 }
 assert.throws(()=>use(st,'TTG-1-041',{targetUids:['a','b']}));
 assert.equal(resolveTtgTurnEnd(r).players[0].front.find(x=>x.uid==='a').currentBp,TTG_BY_ID['TTG-1-009'].bp);
});
test('040 draws two, uses physical removed area, front generation & temporary doubling',()=>{
 const st=s();st.players[0].hand=[c('event','TTG-1-040')];
 st.players[0].deck=[c('d1','TTG-1-005'),c('d2','TTG-1-006'),c('d3','TTG-1-009')];
 st.players[0].front[0]=c('f','TTG-1-019');
 st.players[0].energy[0]=c('generator','TTG-1-033',{gen:8});
 const before=ids(st.players[0]);
 const r=use(st,'TTG-1-040');
 assert.deepEqual(r.players[0].hand.map(x=>x.uid),['d1','d2']);
 assert.deepEqual(r.players[0].removed.map(x=>x.uid),['event']);
 assert.equal(r.players[0].frontGeneratesAll,true);
 assert.deepEqual(ids(r.players[0]),before);
 assert.deepEqual(legalGreenEventActions(r,0).filter(x=>x.cardId==='TTG-1-040'),[]);
 const choices=legalGreen040RemovedActions(r,0);
 assert.deepEqual(choices.map(x=>x.uid),['event']);
 const doubled=resolveGreen040Removed(r,{player:0,uid:'event'});
 assert.equal(doubled.players[0].energyDoublings,1);
 assert.deepEqual(legalGreen040RemovedActions(doubled,0),[]);
 const end=resolveTtgTurnEnd(doubled);
 assert.equal(end.players[0].energyDoublings,0);
 assert.equal(end.players[0].frontGeneratesAll,undefined);
});
test('same green event legal set drives both player dispatch and AI; fail closed on AP',()=>{
 const st=s();st.players[0].hand=[c('event','TTG-1-035')];
 st.players[1].front[0]=c('target','TTG-1-005',{bp:2000});
 const legal=legalTtgRuleActions(st,0).filter(x=>x.type==='playGreenEvent');
 assert.equal(legal.length,1);
 assert.throws(()=>dispatchTtgRuleAction(st,{type:'playGreenEvent',player:0,handUid:'event',cardId:'TTG-1-035',targetUid:'target',payApUids:['rest']}));
 const ai=chooseTtgRuleAiAction(st,0);
 assert.equal(ai.type,'playGreenEvent');
 const r=dispatchTtgRuleAction(st,ai);
 assert.deepEqual(r.players[1].removed.map(x=>x.uid),['target']);
 assert.equal(st.players[1].front[0].uid,'target');
});
